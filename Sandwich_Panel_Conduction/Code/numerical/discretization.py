"""
discretization.py

Finite difference discretization of steady-state
one-dimensional heat conduction.
"""

import numpy as np


def build_localized_generation_system(
    x,
    dx,
    q_dot_v_ebox,
    q_dot_v_heater,
    k_eff,
    x_b,
    x_c,
    T_b1
):
    """
    Build the tridiagonal finite difference system for
    one-dimensional steady-state conduction with
    localized volumetric heat generation.

    Boundary conditions:
        - Dirichlet at x = 0.
        - Neumann at the panel center (symmetry).

    OUTPUTS
    -------
    lower : numpy.ndarray
        Lower diagonal of the matrix.
    diagonal : numpy.ndarray
        Main diagonal of the matrix.
    upper : numpy.ndarray
        Upper diagonal of the matrix.
    rhs : numpy.ndarray
        Right-hand side vector.
    """

    N = len(x)
    if N < 2:
        raise ValueError("The mesh must contain at least 2 nodes.")

    if dx <= 0:
        raise ValueError("The spatial step must be positive.")

    if k_eff <= 0:
        raise ValueError("The effective thermal conductivity must be positive.")

    # --------------------------------------------------------
    # Matrix diagonals
    # --------------------------------------------------------

    lower = np.ones(N - 1)
    diagonal = -2.0 * np.ones(N)
    upper = np.ones(N - 1)

    rhs = np.zeros(N)

    # --------------------------------------------------------
    # Boundary conditions
    # --------------------------------------------------------

    # First node: prescribed temperature
    diagonal[0] = 1.0
    upper[0] = 0.0
    rhs[0] = T_b1

    # Last node: zero temperature gradient
    lower[-1] = 1.0
    diagonal[-1] = -1.0

    # --------------------------------------------------------
    # Internal nodes
    # --------------------------------------------------------

    for i in range(1, N - 1):

        if x[i] < x_b:
            rhs[i] = 0.0

        elif x[i] < x_c:
            rhs[i] = (
                -q_dot_v_ebox * dx**2 / k_eff
            )

        else:
            rhs[i] = (
                -(q_dot_v_ebox + q_dot_v_heater)
                * dx**2 / k_eff
            )

    return lower, diagonal, upper, rhs


def build_ebox_panel_system(
    number_of_nodes,
    dx,
    effective_conductance,
    effective_conductivity,
    panel_thickness,
    ebox_conductance,
    ebox_dissipation,
    ebox_width,
    boundary_temperature_1,
    boundary_temperature_2,
    ebox_start_x,
):
    """
    build_ebox_panel_system builds the coupled steady-state thermal
    system for the sandwich panel and the EBOX.

    INPUTS
    ----------
    number_of_nodes : int
        Number of discretization nodes along the panel.

    dx : float
        Spatial discretization step [m].

    effective_conductance : float
        Effective thermal contact conductance between the panel
        and the EBOX [W/(m² K)].

    effective_conductivity : float
        Effective thermal conductivity of the panel [W/(m K)].

    panel_thickness : float
        Total thickness of the sandwich panel [m].

    ebox_conductance : float
        Thermal contact conductance between the panel and the EBOX
        [W/(m² K)].

    ebox_dissipation : float
        Heat dissipation generated by the EBOX [W].

    ebox_width : float
        Width of the EBOX contact surface [m].

    boundary_temperature_1 : float
        Prescribed temperature at the left boundary of the panel [K].

    boundary_temperature_2 : float
        Prescribed temperature at the right boundary of the panel [K].

    ebox_start_x : float
        Position of the beginning of the EBOX along the panel [m].

    OUTPUTS
    ----------
    A : ndarray of shape (number_of_nodes + 1, number_of_nodes + 1)
        Coefficient matrix of the coupled thermal system. It contains
        the discretized heat conduction equations for the panel nodes
        and the energy balance equation for the EBOX.

    b : ndarray of shape (number_of_nodes + 1,)
        Right-hand-side vector containing the boundary temperatures,
        the internal source terms and the EBOX energy balance term.
    """

    # Determine the EBOX contact nodes.
    matlab_start_node = int(np.floor(ebox_start_x / dx + 1))

    start_idx = matlab_start_node - 1
    end_idx = number_of_nodes - matlab_start_node

    # Additional unknown: EBOX temperature.
    total_unknowns = number_of_nodes + 1

    A = np.zeros((total_unknowns, total_unknowns))
    b = np.zeros(total_unknowns)

    ebox_column = number_of_nodes

    # Coupling coefficient between each panel node and the EBOX.
    gamma = (
        effective_conductance
        * dx**2
        / effective_conductivity
        / panel_thickness
    )

    # Left boundary condition.
    A[0, 0] = 1
    b[0] = boundary_temperature_1

    # Internal panel nodes.
    for i in range(1, number_of_nodes - 1):

        if i == start_idx or i == end_idx:
            # First and last nodes under the EBOX.
            coupling_factor = 0.5

        elif start_idx < i < end_idx:
            # Internal nodes under the EBOX.
            coupling_factor = 1.0

        else:
            # Nodes outside the EBOX "footprint", let's say.
            coupling_factor = 0.0

        A[i, i - 1] = 1
        A[i, i] = -2 - coupling_factor * gamma
        A[i, i + 1] = 1

        A[i, ebox_column] = coupling_factor * gamma

    # Right boundary condition.
    A[number_of_nodes - 1, number_of_nodes - 1] = 1
    b[number_of_nodes - 1] = boundary_temperature_2

    # EBOX energy balance.
    A[ebox_column, start_idx:end_idx + 1] = -1

    # Half weighting at the two ends of the contact region.
    A[ebox_column, start_idx] = -0.5
    A[ebox_column, end_idx] = -0.5

    # Number of intervals covered by the EBOX.
    A[ebox_column, ebox_column] = end_idx - start_idx

    b[ebox_column] = (
        ebox_dissipation
        / (ebox_conductance * dx * ebox_width)
    )

    return A, b